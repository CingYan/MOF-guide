def _level_field(f, *keys):
    for k in keys:
        v = f.get(k)
        if v:
            return v
    return ""


def main():
    with open(WIKI_JSON_PATH, "r", encoding="utf-8") as fh:
        data = json.load(fh)

    skills = data["skills"]
    orig_skill_count = len(skills)
    orig_level_counts = [len(s["levels"]) for s in skills]

    by_en = {m[0]: m for m in MAPPING}

    renamed = []
    skipped_already = []
    mismatched = []

    for s in skills:
        # 已經套用過（有 en 欄位）就用 en 當查找 key，否則用目前的 name。
        lookup_key = s.get("en") or s["name"]
        m = by_en.get(lookup_key)
        if not m:
            continue

        en_name, exp_job, exp_lvl, cn_name, evidence = m

        if s.get("en") == en_name and s["name"] == cn_name:
            # 已經套用過，且狀態正確，跳過（保持可重跑）。
            skipped_already.append(en_name)
            continue

        # 套用前再驗證一次職業／等級證據是否仍然吻合，不吻合就不要硬套。
        lv0 = s["levels"][0]
        f0 = lv0.get("f", {})
        actual_job = _level_field(f0, "職業", "需求職業")
        actual_lvl = _level_field(f0, "等級", "需求等級")
        if actual_job != exp_job or actual_lvl != exp_lvl:
            mismatched.append((en_name, exp_job, exp_lvl, actual_job, actual_lvl))
            continue

        s["en"] = en_name
        s["name"] = cn_name

        for lv in s["levels"]:
            old_name = lv["name"]
            if old_name == en_name:
                lv["name"] = cn_name
            elif old_name.startswith(en_name + " "):
                suffix = old_name[len(en_name):]  # 例如 " I" / " II"
                lv["name"] = cn_name + suffix
            # 名稱對不上（例如資料本身有誤植，如 Enchanted Arrow 的重複區塊
            # 誤植成 Instant Arrow）就保持原樣，不亂改。

        renamed.append(en_name)

    # ---- 安全檢查：確保沒有弄丟資料 ----
    assert len(skills) == orig_skill_count, "skills 筆數變了！"
    new_level_counts = [len(s["levels"]) for s in skills]
    assert new_level_counts == orig_level_counts, "有技能的 levels 筆數變了！"

    with open(WIKI_JSON_PATH, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))

    print(f"技能總數：{orig_skill_count}（不變）")
    print(f"本次改名：{len(renamed)} 個")
    print(f"已改過、本次跳過：{len(skipped_already)} 個")
    if mismatched:
        print(f"警告：{len(mismatched)} 筆對照表資料跟目前 wiki.json 對不上，已跳過未套用：",
              file=sys.stderr)
        for row in mismatched:
            print(f"  - {row}", file=sys.stderr)
    untouched = orig_skill_count - len(renamed) - len(skipped_already)
    print(f"保留英文原名：{untouched} 個")


if __name__ == "__main__":
    main()
